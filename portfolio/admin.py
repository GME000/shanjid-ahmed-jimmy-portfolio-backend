from django.contrib import admin
from .models import *
@admin.register(Profile)
class ProfileAdmin(admin.ModelAdmin): list_display=("full_name","email","is_available_for_hire"); search_fields=("full_name","email")
@admin.register(Skill)
class SkillAdmin(admin.ModelAdmin): list_display=("name","category","proficiency","is_featured"); search_fields=("name",); list_filter=("category","is_featured")
@admin.register(Experience)
class ExperienceAdmin(admin.ModelAdmin): list_display=("company","role","start_date","is_current"); search_fields=("company","role"); list_filter=("employment_type","is_current")
@admin.register(Education)
class EducationAdmin(admin.ModelAdmin): list_display=("institution","degree","start_year"); search_fields=("institution","degree")
@admin.register(Project)
class ProjectAdmin(admin.ModelAdmin): list_display=("title","category","is_featured","completed_date"); search_fields=("title","summary"); list_filter=("category","is_featured")
@admin.register(Category)
class CategoryAdmin(admin.ModelAdmin): list_display=("name","slug"); search_fields=("name",)
@admin.register(Tag)
class TagAdmin(admin.ModelAdmin): list_display=("name","slug"); search_fields=("name",)
@admin.register(Post)
class PostAdmin(admin.ModelAdmin): list_display=("title","status","author","published_at","views_count"); search_fields=("title","content"); list_filter=("status","is_featured","category")
@admin.register(PostLike)
class PostLikeAdmin(admin.ModelAdmin): list_display=("post","visitor_id","created_at"); search_fields=("visitor_id",)
@admin.register(Comment)
class CommentAdmin(admin.ModelAdmin): list_display=("post","name","is_approved","created_at"); search_fields=("name","email","content"); list_filter=("is_approved",)
@admin.register(ContactMessage)
class ContactAdmin(admin.ModelAdmin): list_display=("name","email","subject","is_read","created_at"); search_fields=("name","email","subject"); list_filter=("is_read",)
